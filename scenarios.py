# ─── Criterion 3 — mixed human/AI passages ───────────────────────────────────
# The opening of a human passage joined to the closing of an AI passage. A real
# mixed piece is written this way: someone starts it themselves and lets a tool
# finish, or the other way round.

def _first_half(text: str) -> str:
    words = text.split()
    return " ".join(words[: len(words) // 2])


def _second_half(text: str) -> str:
    words = text.split()
    return " ".join(words[len(words) // 2:])


